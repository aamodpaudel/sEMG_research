"""Phoneme targets and a pronunciation lexicon (as in Gaddy & Klein 2021).

Pronunciations come from a subset of the CMU Pronouncing Dictionary (BSD-2-Clause, see the
header of vocab/cmudict_subset.txt), with stress marks removed (39 ARPAbet phones). Words that
CMUdict lacks were given one pronunciation by g2p_en (Apache-2.0) when the subset was built;
those lines are marked "g2p". The subset covers every word in the Gaddy transcripts and in
vocab/commands.json. Other words fall back to g2p_en at run time if it is installed, else to a
crude letter-to-sound rule (only used for words outside the bundled file).

    python -m semg.phonemes --cmudict path/to/cmudict.dict     # rebuild vocab/cmudict_subset.txt
"""
import argparse
import json
import os
import re

PHONES = ("AA AE AH AO AW AY B CH D DH EH ER EY F G HH IH IY JH K L M N NG OW OY P R S SH T TH "
          "UH UW V W Y Z ZH").split()
BLANK = 0
SEP = 1                                   # word boundary, plays the role of the space character
TOKENS = ["<blank>", "|"] + PHONES
TOKEN_TO_ID = {p: i for i, p in enumerate(TOKENS)}
N_TOKENS = len(TOKENS)
LEXICON_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "vocab", "cmudict_subset.txt")

_LEX = None
_G2P = None
_LETTER = {"a": "AE", "b": "B", "c": "K", "d": "D", "e": "EH", "f": "F", "g": "G", "h": "HH", "i": "IH", "j": "JH",
           "k": "K", "l": "L", "m": "M", "n": "N", "o": "AA", "p": "P", "q": "K", "r": "R", "s": "S", "t": "T",
           "u": "AH", "v": "V", "w": "W", "x": "K", "y": "Y", "z": "Z"}


def _strip(ph):
    return [re.sub(r"\d", "", p) for p in ph if re.sub(r"\d", "", p) in TOKEN_TO_ID]


def load_lexicon(path=LEXICON_FILE):
    """word -> list of phones (first pronunciation)."""
    global _LEX
    if _LEX is None or path != LEXICON_FILE:
        lex = {}
        with open(path, encoding="utf-8") as f:
            for line in f:
                if line.startswith(";;;") or not line.strip():
                    continue
                parts = line.split()
                w, ph = parts[0], [p for p in parts[1:] if p != "g2p"]
                lex.setdefault(w, ph)
        if path != LEXICON_FILE:
            return lex
        _LEX = lex
    return _LEX


def _g2p(word):
    global _G2P
    if _G2P is None:
        try:
            from g2p_en import G2p
            _G2P = G2p()
        except Exception:
            _G2P = False
    if _G2P:
        ph = _strip(_G2P(word))
        if ph:
            return ph
    out = []
    for c in word:
        p = _LETTER.get(c)
        if p and (not out or out[-1] != p):
            out.append(p)
    return out or ["AH"]


def pronounce(word):
    lex = load_lexicon()
    if word not in lex:
        lex[word] = _g2p(word)
    return lex[word]


def encode_phones(text):
    """Normalised text -> phone token ids with SEP between words."""
    out = []
    for i, w in enumerate(text.split()):
        if i:
            out.append(SEP)
        out.extend(TOKEN_TO_ID[p] for p in pronounce(w))
    return out


def build_subset(cmudict_path, words, out=LEXICON_FILE):
    full = {}
    with open(cmudict_path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip()
            if not line:
                continue
            w, *ph = line.split()
            w = re.sub(r"\(\d+\)$", "", w)
            if w in words and w not in full:
                full[w] = _strip(ph)
    missing = sorted(set(words) - set(full))
    from g2p_en import G2p
    g2p = G2p()
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(";;; Subset of the CMU Pronouncing Dictionary 0.7b (cmudict 1.1.3), stress removed.\n"
                ";;; Copyright (C) 1993-2015 Carnegie Mellon University. All rights reserved.\n"
                ";;; Redistribution and use in source and binary forms, with or without modification, are permitted\n"
                ";;; provided that redistributions of source code retain the above copyright notice (BSD-2-Clause;\n"
                ";;; full text: https://github.com/cmusphinx/cmudict/blob/master/LICENSE).\n"
                ";;; Lines ending in 'g2p' are not from CMUdict: generated by g2p_en (Apache-2.0) for words it lacks.\n")
        for w in sorted(full):
            f.write(w + " " + " ".join(full[w]) + "\n")
        for w in missing:
            f.write(w + " " + " ".join(_strip(g2p(w)) or ["AH"]) + " g2p\n")
    return len(full), len(missing)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cmudict", required=True)
    ap.add_argument("--index", default="data/index.json")
    args = ap.parse_args()
    from .data import load_index
    words = {w for u in load_index(args.index) for w in u.text.split()}
    with open("vocab/commands.json", encoding="utf-8") as f:
        for g in json.load(f)["groups"].values():
            for p in g:
                words |= set(p.split())
    print("cmudict %d, g2p %d" % build_subset(args.cmudict, words))


if __name__ == "__main__":
    main()
